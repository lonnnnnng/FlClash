#!/usr/bin/env node
// 作者 long：所有手机图标从同一SVG派生，避免旧系统、圆形桌面和自适应图标出现不同品牌或比例。
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const projectRoot = path.resolve(__dirname, '..');
const moduleFlag = process.argv.indexOf('--sharp-module');
const sharp = require(moduleFlag < 0 ? 'sharp' : process.argv[moduleFlag + 1]);
const sourcePath = path.join(projectRoot, 'assets/branding/kclash-icon.svg');
const source = fs.readFileSync(sourcePath, 'utf8');
const sourceSha256 = crypto.createHash('sha256').update(source).digest('hex');
const background = source.match(/<rect[^>]*fill="(#[0-9A-Fa-f]{6})"/)[1];
const paths = [...source.matchAll(/<path fill="(#[0-9A-Fa-f]{6})" d="([^"]+)"\s*\/>/g)]
  .map((match) => ({ fill: match[1], data: match[2] }));
if (paths.length !== 3) throw new Error('折流K源稿必须包含主干、完整折线与下折面三条路径');
const svg = (body, viewport = '0 0 108 108') =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="108" height="108" viewBox="${viewport}">${body}</svg>`;
const foreground = paths.map(({ fill, data }) => `<path fill="${fill}" d="${data}"/>`).join('');
const origin = `KClash Fold K; authored vector selected by user 2026-11-19; assets/branding/kclash-icon.svg SHA256 ${sourceSha256}; generated by tool/generate_kclash_launcher.cjs`;
const generated = '<!-- 作者 long：由 tool/generate_kclash_launcher.cjs 从品牌SVG生成，请修改源稿后重新生成。 -->';

function write(relative, contents) {
  const target = path.join(projectRoot, relative);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, contents);
}

function vector(entries) {
  return `<?xml version="1.0" encoding="utf-8"?>\n${generated}\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n${entries.map(({ fill, data }) => `    <path android:fillColor="${fill}" android:pathData="${data}"/>`).join('\n')}\n</vector>\n`;
}

function masked(shape, monochrome = false, tone = '#173F36', ground = '#C6EDDA') {
  const mask = shape === 'circle'
    ? '<circle cx="54" cy="54" r="36"/>'
    : `<rect x="18" y="18" width="72" height="72" rx="${shape === 'rounded' ? 17 : 0}"/>`;
  const mark = monochrome
    ? paths.slice(0, 2).map(({ data }) => `<path fill="${tone}" d="${data}"/>`).join('')
    : foreground;
  return svg(`<defs><clipPath id="mask">${mask}</clipPath></defs><g clip-path="url(#mask)"><rect width="108" height="108" fill="${monochrome ? ground : background}"/>${mark}</g>`, '18 18 72 72');
}

async function raster(input, size, target, webp = false) {
  let output = sharp(Buffer.from(input), { density: 576 }).resize(size, size);
  output = webp ? output.webp({ lossless: true }) : output.png();
  // 作者 long：位图保留源稿哈希与生成来源，后续重绘或同步上游时能确定它属于Kotlin独立品牌。
  await output.withXmp(`<?xpacket begin="﻿"?><x:xmpmeta xmlns:x="adobe:ns:meta/"><rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#"><rdf:Description xmlns:dc="http://purl.org/dc/elements/1.1/" dc:source="${origin}"/></rdf:RDF></x:xmpmeta><?xpacket end="w"?>`).toFile(path.join(projectRoot, target));
}

async function main() {
  write('android/app/src/main/res/drawable/ic_launcher_foreground.xml', vector(paths));
  // 作者 long：主题图标只取主干和完整折线；彩色下折面不参与透明度计算，系统着色后轮廓仍完整。
  write('android/app/src/main/res/drawable/ic_launcher_monochrome.xml', vector(paths.slice(0, 2).map(({ data }) => ({ fill: '#FFFFFF', data }))));
  // 作者 long：TV仍共用旧背景资源，手机版独立命名防止此次重绘改变范围外的TV外观。
  write('android/app/src/main/res/values/kclash_launcher_background.xml', `<?xml version="1.0" encoding="utf-8"?>\n${generated}\n<resources>\n    <color name="kclash_launcher_background">${background}</color>\n</resources>\n`);
  const adaptive = `<?xml version="1.0" encoding="utf-8"?>\n${generated}\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n    <background android:drawable="@color/kclash_launcher_background"/>\n    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n</adaptive-icon>\n`;
  for (const name of ['ic_launcher', 'ic_launcher_round']) write(`android/app/src/main/res/mipmap-anydpi-v26/${name}.xml`, adaptive);
  const densities = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
  for (const [density, size] of Object.entries(densities)) {
    for (const round of [false, true]) {
      await raster(masked(round ? 'circle' : 'square'), size, `android/app/src/main/res/mipmap-${density}/ic_launcher${round ? '_round' : ''}.webp`, true);
    }
  }
  await raster(masked('square'), 512, 'android/app/src/main/ic_launcher-playstore.png');
  await raster(masked('square'), 1024, 'assets/branding/kclash-icon-1024.png');
  const specimens = [
    ['square', false, 'Square'], ['circle', false, 'Circle'], ['rounded', false, 'Rounded'],
    ['circle', true, 'Themed light'], ['rounded', true, 'Themed dark'],
  ];
  const cells = [];
  for (let i = 0; i < specimens.length; i++) {
    const [shape, mono] = specimens[i];
    cells.push({ input: await sharp(Buffer.from(masked(shape, mono, i === 4 ? '#D6F5E4' : '#173F36', i === 4 ? '#25483E' : '#C6EDDA'))).resize(160, 160).png().toBuffer(), left: 40 + 224 * i, top: 60 });
  }
  const labels = svg('<rect width="1160" height="300" fill="#EEF1F3"/>' + specimens.map((entry, i) => `<text x="${40 + 224 * i}" y="260" font-family="Arial,sans-serif" font-size="18" fill="#46565F">${entry[2]}</text>`).join(''), '0 0 1160 300').replace('width="108" height="108"', 'width="1160" height="300"');
  await sharp(Buffer.from(labels)).composite(cells).png().toFile(path.join(projectRoot, 'docs/branding/kclash-icon-masks.png'));
  write('assets/branding/provenance.json', JSON.stringify({ name: 'KClash 折流 K', selectedByUser: '2026-11-19', source: 'assets/branding/kclash-icon.svg', sourceSha256, generator: 'tool/generate_kclash_launcher.cjs', rasterizer: `sharp ${sharp.versions.sharp}`, colors: { background, foreground: paths[0].fill, fold: paths[2].fill }, scope: 'Android phone launcher only; adaptive, legacy square/round, monochrome and store export' }, null, 2) + '\n');
  console.log(`Generated KClash phone launcher assets from ${sourceSha256}`);
}
main().catch((error) => { console.error(error.message); process.exitCode = 1; });
