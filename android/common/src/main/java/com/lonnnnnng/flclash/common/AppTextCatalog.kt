    val patterns: List<Template> by lazy {
        ids.entries.filter { Regex("\\{\\d+\\}").containsMatchIn(it.key) }
            .sortedByDescending { it.key.length }.map { (source, resource) ->
                val parameters = mutableListOf<Int>()
                var previous = 0
                val pattern = buildString {
                    Regex("\\{(\\d+)\\}").findAll(source).forEach { token ->
                        append(Regex.escape(source.substring(previous, token.range.first)))
                        append("(.*?)")
                        parameters += token.groupValues[1].toInt()
                        previous = token.range.last + 1
                    }
                    append(Regex.escape(source.substring(previous)))
                }
                Template(Regex(pattern, RegexOption.DOT_MATCHES_ALL), resource, parameters)
            }
    }
